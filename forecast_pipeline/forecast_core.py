#!/usr/bin/env python3
"""Shared decoding, compact-output and independent QA helpers.

Published tracks are generated by :mod:`forecast_pipeline.v56_tracking`, which
calls the frozen catalogue detector and linker directly.  The small
vorticity/pressure tracker retained here is an independent model-neutral QA
cross-check only; its coordinates are never published.
"""

